"""Structured rule representation with an explicit review lifecycle.

Rules are data, never generated by an LLM. Only rules in ``active`` status are
authoritative; ``reviewed`` rules may run in demo mode with a visible warning.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class RuleStatus(str, Enum):
    DRAFT = "draft"
    REVIEWED = "reviewed"
    ACTIVE = "active"
    DEPRECATED = "deprecated"


class Operator(str, Enum):
    LE = "<="
    LT = "<"
    GE = ">="
    GT = ">"
    EQ = "=="
    NE = "!="
    IN = "in"
    NOT_IN = "not_in"


class Expr(BaseModel):
    model_config = ConfigDict(extra="forbid")

    op: Literal["add", "sub", "mul", "div"]
    args: list["Operand"]

    @model_validator(mode="after")
    def _check_arity(self) -> "Expr":
        if len(self.args) < 2:
            raise ValueError("expression requires at least two arguments")
        return self


class Operand(BaseModel):
    """One of: a literal constant, a named fact, a subgoal value, or an arithmetic expression."""

    model_config = ConfigDict(extra="forbid")

    const: Any = None
    fact: str | None = None
    goal_value: str | None = None
    expr: Expr | None = None

    @model_validator(mode="after")
    def _exactly_one(self) -> "Operand":
        provided = [k for k in ("const", "fact", "goal_value", "expr") if getattr(self, k) is not None]
        if len(provided) != 1:
            raise ValueError("operand must define exactly one of const/fact/goal_value/expr")
        return self


class Condition(BaseModel):
    model_config = ConfigDict(extra="forbid")

    left: Operand
    operator: Operator
    right: Operand | None = None
    unit: str | None = None
    description: str | None = None

    @model_validator(mode="after")
    def _required_right(self) -> "Condition":
        if self.operator not in (Operator.IN, Operator.NOT_IN) and self.right is None:
            raise ValueError(f"operator {self.operator.value} requires a right-hand operand")
        return self

    def render(self) -> str:
        from app.expert_system.rule_engine import render_operand

        text = f"{render_operand(self.left)} {self.operator.value}"
        if self.right is not None:
            text += f" {render_operand(self.right)}"
        if self.unit:
            text += f" [{self.unit}]"
        return text


class EvidenceSpan(BaseModel):
    model_config = ConfigDict(extra="forbid")

    page: int | None = None
    start_char: int | None = Field(default=None, ge=0)
    end_char: int | None = Field(default=None, ge=0)


class RuleSource(BaseModel):
    model_config = ConfigDict(extra="forbid")

    document_id: str
    document: str
    issue: str
    article: str
    page: int | None = None
    quote: str
    evidence_span: EvidenceSpan | None = None

    @model_validator(mode="after")
    def _source_complete(self) -> "RuleSource":
        if not self.quote.strip():
            raise ValueError("rule source quote must not be empty")
        return self


class RuleValidation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    verified_against: str
    verified_on: str
    method: str
    reviewer: str | None = None
    reviewed_at: str | None = None
    human_approved: bool = False
    test_case_ids: list[str] = Field(default_factory=list)
    notes: str | None = None


class Conclusion(BaseModel):
    model_config = ConfigDict(extra="forbid")

    goal: str
    kind: Literal["boolean", "value"]
    value: bool | float | int | str | None = None
    unit: str | None = None
    expr: Expr | None = None

    @model_validator(mode="after")
    def _consistent(self) -> "Conclusion":
        if self.kind == "boolean":
            if not isinstance(self.value, bool):
                raise ValueError("boolean conclusion requires a boolean 'value'")
            if self.expr is not None:
                raise ValueError("boolean conclusion cannot use an expression")
        else:
            if self.value is None and self.expr is None:
                raise ValueError("value conclusion requires 'value' or 'expr'")
        return self


class Rule(BaseModel):
    model_config = ConfigDict(extra="forbid")

    rule_id: str
    name: str
    source: RuleSource
    applies_if: list[Condition] = Field(default_factory=list)
    conditions: list[Condition] = Field(default_factory=list)
    conclusion: Conclusion
    status: RuleStatus = RuleStatus.DRAFT
    validation: RuleValidation | None = None
    notes: str | None = None

    @model_validator(mode="after")
    def _lifecycle_requirements(self) -> "Rule":
        if self.status in (RuleStatus.REVIEWED, RuleStatus.ACTIVE):
            if self.validation is None:
                raise ValueError(f"rule {self.rule_id} in status {self.status.value} requires validation metadata")
            if not self.validation.human_approved and self.status is RuleStatus.ACTIVE:
                raise ValueError(f"rule {self.rule_id} cannot be active without human approval")
        if self.status is RuleStatus.ACTIVE:
            assert self.validation is not None
            missing = [
                field
                for field in ("reviewer", "reviewed_at", "verified_against", "verified_on", "method")
                if not getattr(self.validation, field)
            ]
            if missing:
                raise ValueError(f"active rule {self.rule_id} missing validation fields: {', '.join(missing)}")
        return self

    @property
    def goal(self) -> str:
        return self.conclusion.goal

    def is_runnable(self, allow_reviewed: bool = False) -> bool:
        return self.status is RuleStatus.ACTIVE or (
            allow_reviewed and self.status is RuleStatus.REVIEWED
        )

    @property
    def is_demo(self) -> bool:
        return self.status is RuleStatus.REVIEWED


class RuleSet(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: str
    regulation: str
    regulation_issue: str
    document_id: str
    scope: str | None = None
    subdomain: str | None = None
    rules: list[Rule]

    @model_validator(mode="after")
    def _unique_ids(self) -> "RuleSet":
        ids = [r.rule_id for r in self.rules]
        duplicates = {rid for rid in ids if ids.count(rid) > 1}
        if duplicates:
            raise ValueError(f"duplicate rule ids: {sorted(duplicates)}")
        return self
